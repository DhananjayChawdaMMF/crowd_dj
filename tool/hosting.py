#!/usr/bin/env python3
"""Single source of truth for hosting config. Regenerates:
  firebase.json, vercel.json, netlify.toml, docs/deploy/nginx.conf

Run after changing headers:  python3 tool/hosting.py
Also imported by tool/serve_build.py so local verification uses the same headers.

The app is built with `--no-web-resources-cdn` (see tool/build_web.sh), so
CanvasKit and fallback fonts are served from the app's own origin and the CSP
needs no third-party hosts except your Supabase project.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

CSP = "; ".join([
    "default-src 'self'",
    "script-src 'self' 'wasm-unsafe-eval'",  # CanvasKit is WebAssembly
    "style-src 'self' 'unsafe-inline'",      # Flutter injects styles
    "img-src 'self' data: blob: https:",     # https artwork only (enforced server-side too)
    "font-src 'self' data:",
    "media-src 'self' blob:",
    "connect-src 'self' https://*.supabase.co wss://*.supabase.co data: blob:",
    "worker-src 'self' blob:",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
])

SECURITY = {
    "Content-Security-Policy": CSP,
    "X-Content-Type-Options": "nosniff",
    "X-Frame-Options": "DENY",
    "Referrer-Policy": "strict-origin-when-cross-origin",
    "Permissions-Policy": "camera=(), microphone=(), geolocation=(), payment=(), usb=()",
    "Cross-Origin-Opener-Policy": "same-origin",
    "Strict-Transport-Security": "max-age=63072000; includeSubDomains",
}

# Entry files are not content-hashed: always revalidate (cheap 304s), or users
# keep running a stale build after a deploy.
NO_CACHE = "no-cache"
# Big static payloads: cache, but revalidate in the background.
STATIC = "public, max-age=86400, stale-while-revalidate=604800"

NO_CACHE_FILES = ["index.html", "flutter_bootstrap.js", "flutter.js", "main.dart.js",
                  "flutter_service_worker.js", "version.json", "manifest.json", "splash.js"]
STATIC_DIRS = ["assets", "canvaskit", "icons"]


def firebase():
    headers = [{"source": "**", "headers": [{"key": k, "value": v} for k, v in SECURITY.items()]}]
    headers += [{"source": f"/{f}", "headers": [{"key": "Cache-Control", "value": NO_CACHE}]} for f in NO_CACHE_FILES]
    headers += [{"source": f"/{d}/**", "headers": [{"key": "Cache-Control", "value": STATIC}]} for d in STATIC_DIRS]
    return {"hosting": {
        "public": "build/web",
        "ignore": ["firebase.json", "**/.*", "**/node_modules/**"],
        # Deep links (/room/<code>) must serve the app shell.
        "rewrites": [{"source": "**", "destination": "/index.html"}],
        "headers": headers,
    }}


def vercel():
    headers = [{"source": "/(.*)", "headers": [{"key": k, "value": v} for k, v in SECURITY.items()]}]
    headers += [{"source": f"/{f}", "headers": [{"key": "Cache-Control", "value": NO_CACHE}]} for f in NO_CACHE_FILES]
    headers += [{"source": f"/{d}/(.*)", "headers": [{"key": "Cache-Control", "value": STATIC}]} for d in STATIC_DIRS]
    return {
        "outputDirectory": "build/web",
        # Real files win; everything else (deep links) gets the app shell.
        "rewrites": [{"source": "/((?!assets/|canvaskit/|icons/|.*\\..*).*)", "destination": "/index.html"}],
        "headers": headers,
    }


def netlify():
    out = ["# Generated by tool/hosting.py. Do not edit by hand.", "[build]", '  publish = "build/web"', "",
           "# Deep links (/room/<code>) must serve the app shell.",
           "[[redirects]]", '  from = "/*"', '  to = "/index.html"', "  status = 200", ""]
    out += ["[[headers]]", '  for = "/*"', "  [headers.values]"]
    out += [f'    {k} = "{v}"' for k, v in SECURITY.items()]
    out.append("")
    for f in NO_CACHE_FILES:
        out += ["[[headers]]", f'  for = "/{f}"', "  [headers.values]", f'    Cache-Control = "{NO_CACHE}"', ""]
    for d in STATIC_DIRS:
        out += ["[[headers]]", f'  for = "/{d}/*"', "  [headers.values]", f'    Cache-Control = "{STATIC}"', ""]
    return "\n".join(out)


def nginx():
    sec = "\n".join(f'    add_header {k} "{v}" always;' for k, v in SECURITY.items())
    nc = "|".join(f.replace(".", r"\.") for f in NO_CACHE_FILES)
    dirs = "|".join(STATIC_DIRS)
    return f"""# Generated by tool/hosting.py. Do not edit by hand.
# Example server block for serving build/web behind nginx (TLS terminated here or upstream).
server {{
    listen 80;
    server_name crowddj.example.com;
    root /var/www/crowddj;   # contents of build/web
    index index.html;

    gzip on;
    gzip_types text/css application/javascript application/json image/svg+xml application/wasm;

{sec}

    # Entry files are not content-hashed: always revalidate.
    location ~ ^/({nc})$ {{
        add_header Cache-Control "{NO_CACHE}" always;
{sec}
    }}

    location ~ ^/({dirs})/ {{
        add_header Cache-Control "{STATIC}" always;
{sec}
    }}

    # Deep links (/room/<code>) must serve the app shell.
    location / {{
        try_files $uri $uri/ /index.html;
    }}
}}
"""


if __name__ == "__main__":
    (ROOT / "firebase.json").write_text(json.dumps(firebase(), indent=2) + "\n")
    (ROOT / "vercel.json").write_text(json.dumps(vercel(), indent=2) + "\n")
    (ROOT / "netlify.toml").write_text(netlify() + "\n")
    (ROOT / "docs/deploy/nginx.conf").write_text(nginx())
    print("wrote firebase.json vercel.json netlify.toml docs/deploy/nginx.conf")
